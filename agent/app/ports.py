"""可抽換介面。POC 實作見 adapters.py；正式版替換對應 adapter 即可。"""
from typing import Protocol


class LLMProvider(Protocol):          # Mock / OpenAI-compat / Anthropic -> vLLM / Ollama
    name: str
    async def plan(self, ctx: dict) -> dict: ...
    async def report(self, ctx: dict) -> str: ...
    async def chat_plan(self, text: str, history: list) -> list: ...
    async def chat_answer(self, text: str, results: list) -> str: ...


class ObservabilityPort(Protocol):    # SQLite -> Loki / Prometheus / Tempo
    def ingest(self, logs: list, metrics: list, spans: list) -> None: ...
    def logs(self, lane=None, contains=None, since=0, limit=20) -> list: ...
    def count_logs(self, lane=None, contains=None, since=0) -> int: ...
    def metrics(self, lane, name, since=0, limit=None) -> list: ...
    def spans(self, lane=None, since=0, status=None, limit=10) -> list: ...


class KnowledgePort(Protocol):        # FTS5 -> 向量庫 + bge-m3
    def index(self, title: str, body: str, kind: str) -> None: ...
    def search(self, query: str, k: int = 3) -> list: ...


class IssueStore(Protocol):           # SQLite -> Postgres / 雲端
    def create(self, lane: int, kind: str) -> int: ...
    def event(self, issue_id, type_: str, text: str) -> int: ...


class VersionStore(Protocol):         # SQLite -> Git / S3 / 設定中心
    def head(self) -> dict | None: ...
    def get(self, seq: int) -> dict | None: ...
    def add(self, content: dict, parent, actor: str, reason: str, issue_id, ts=None) -> dict: ...


class Notifier(Protocol):             # outbox -> PagerDuty / LINE / Slack
    def notify(self, target: str, payload: dict) -> None: ...
