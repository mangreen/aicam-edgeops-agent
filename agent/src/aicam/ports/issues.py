"""IssueStore：issue、事件時間軸、action、升級請求、對話。POC：SQLite；正式版：Postgres。"""
from typing import Protocol


class IssueStore(Protocol):
    def create(self, lane: int, kind: str) -> int: ...
    def event(self, issue_id, type_: str, text: str) -> int: ...
    def events(self, after: int = 0, limit: int = 200, issue_id=None) -> list: ...
