"""EdgeControlPort：對邊緣端下達修復動作。POC：sim 控制 API；正式版：真實邊緣控制通道。"""
from typing import Protocol


class EdgeControlPort(Protocol):
    async def restart_pipeline(self, lane: int) -> dict: ...
    async def reconnect_stream(self, lane: int) -> dict: ...
    async def physical_fix(self, lane: int) -> dict: ...
    async def push_config(self, cfg: dict) -> dict: ...
    async def fault(self, name: str, lane: int = 1) -> dict: ...
    async def reset(self) -> dict: ...
